'use client';

import { useState, useEffect, useRef, useMemo } from 'react';
import { Box } from '@mui/material';
import { useLanguage } from '@/contexts/LanguageContext';

interface BaseBanner {
  id: string;
  // Image per language; falls back to English when a language is missing.
  images: { en: string; gu?: string };
  altKey: string;
}

// Promotes a menu item; tapping it jumps to that item in the menu.
// Hidden while the item is unavailable.
interface ItemBanner extends BaseBanner {
  type: 'item';
  menuItemId: string;
}

// Offers, announcements and other banners not tied to a menu item
interface PromoBanner extends BaseBanner {
  type: 'promo';
}

type Banner = ItemBanner | PromoBanner;

// Banners are generated by scripts/generate-banners.mjs into public/banners/
const BANNERS: Banner[] = [
  {
    type: 'promo',
    id: 'discount-10',
    images: { en: '/banners/discount-10-en.png', gu: '/banners/discount-10-gu.png' },
    altKey: 'banner.discount10Alt',
  },
  {
    type: 'item',
    id: 'mysore-masala-dosa',
    menuItemId: '7ce2d921-2949-4c64-9b07-3000148b68db', // Mysore Masala Dosai (Ghee)
    images: { en: '/banners/mysore-masala-dosa-en.png', gu: '/banners/mysore-masala-dosa-gu.png' },
    altKey: 'banner.mysoreMasalaDosaAlt',
  },
  {
    type: 'item',
    id: 'kumbakonam-coffee',
    menuItemId: 'befec875-49f5-4c99-90f8-9d59d1e5a388', // Sugarfree Kumbakonam filter coffee
    images: { en: '/banners/kumbakonam-coffee-en.png', gu: '/banners/kumbakonam-coffee-gu.png' },
    altKey: 'banner.kumbakonamCoffeeAlt',
  },
  {
    type: 'item',
    id: 'idiyappam-kurma',
    menuItemId: '1ad5a12e-3869-43fb-8f94-26dc2304f7d1', // Weekend Special - Idiyappam with vegetable kurma
    images: { en: '/banners/idiyappam-kurma-en.png', gu: '/banners/idiyappam-kurma-gu.png' },
    altKey: 'banner.idiyappamKurmaAlt',
  },
];

const AUTO_ADVANCE_MS = 5000;

interface BannerCarouselProps {
  // IDs of menu items currently on the menu; item banners for anything else are hidden
  availableItemIds: string[];
  onItemBannerClick: (menuItemId: string) => void;
}

export default function BannerCarousel({ availableItemIds, onItemBannerClick }: BannerCarouselProps) {
  const { language, t } = useLanguage();
  const banners = useMemo(
    () => BANNERS.filter((banner) => banner.type === 'promo' || availableItemIds.includes(banner.menuItemId)),
    [availableItemIds]
  );
  const [activeIndex, setActiveIndex] = useState(0);
  const trackRef = useRef<HTMLDivElement>(null);
  // True while a finger is on the carousel, so auto-advance doesn't fight a swipe
  const touchingRef = useRef(false);

  // Auto-advance only when there is more than one banner.
  // Restarts whenever the active banner changes, so a swipe gets a full interval.
  useEffect(() => {
    if (banners.length < 2) return;
    const timer = setInterval(() => {
      if (touchingRef.current) return;
      const next = (activeIndex + 1) % banners.length;
      const track = trackRef.current;
      if (track) {
        track.scrollTo({ left: next * track.clientWidth, behavior: 'smooth' });
      }
    }, AUTO_ADVANCE_MS);
    return () => clearInterval(timer);
  }, [activeIndex, banners.length]);

  const handleScroll = () => {
    const track = trackRef.current;
    if (!track) return;
    setActiveIndex(Math.round(track.scrollLeft / track.clientWidth));
  };

  const goTo = (index: number) => {
    const track = trackRef.current;
    if (track) {
      track.scrollTo({ left: index * track.clientWidth, behavior: 'smooth' });
    }
  };

  return (
    <Box>
      <Box
        ref={trackRef}
        onScroll={handleScroll}
        onTouchStart={() => { touchingRef.current = true; }}
        onTouchEnd={() => { touchingRef.current = false; }}
        onTouchCancel={() => { touchingRef.current = false; }}
        sx={{
          display: 'flex',
          overflowX: 'auto',
          scrollSnapType: 'x mandatory',
          WebkitOverflowScrolling: 'touch',
          overscrollBehaviorX: 'contain',
          borderRadius: 2,
          boxShadow: '0 2px 8px rgba(0,0,0,0.12)',
          scrollbarWidth: 'none',
          '&::-webkit-scrollbar': { display: 'none' },
        }}
      >
        {banners.map((banner) => (
          <Box
            key={banner.id}
            component="img"
            src={(language === 'gu' && banner.images.gu) || banner.images.en}
            alt={t(banner.altKey)}
            draggable={false}
            onClick={banner.type === 'item' ? () => onItemBannerClick(banner.menuItemId) : undefined}
            sx={{
              cursor: banner.type === 'item' ? 'pointer' : 'default',
              flex: '0 0 100%',
              width: '100%',
              aspectRatio: '2 / 1',
              objectFit: 'cover',
              scrollSnapAlign: 'start',
              display: 'block',
            }}
          />
        ))}
      </Box>

      {banners.length > 1 && (
        <Box sx={{ display: 'flex', justifyContent: 'center', gap: 0.75, mt: 1 }}>
          {banners.map((banner, index) => (
            <Box
              key={banner.id}
              onClick={() => goTo(index)}
              sx={{
                width: index === activeIndex ? 18 : 6,
                height: 6,
                borderRadius: 3,
                bgcolor: index === activeIndex ? 'primary.main' : 'grey.400',
                transition: 'all 0.3s ease',
                cursor: 'pointer',
              }}
            />
          ))}
        </Box>
      )}
    </Box>
  );
}
